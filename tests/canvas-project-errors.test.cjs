const { test, after } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { buildSync } = require('esbuild')
const dir = mkdtempSync(join(tmpdir(), 'canvas-errors-test-'))
const bundle = join(dir, 'errors.cjs')
buildSync({ entryPoints: ['src/renderer/src/features/canvas-project-errors.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: bundle, logLevel: 'silent' })
const { canvasProjectListError } = require(bundle)
after(() => rmSync(dir, { recursive: true, force: true }))
test('旧预加载接口和缺失主进程处理器提示完整重启', () => {
  assert.match(canvasProjectListError(new TypeError('not a function'), false), /重新启动/)
  assert.match(canvasProjectListError(new Error("Error invoking remote method 'whiteboard:canvas-project-list': Error: No handler registered for 'whiteboard:canvas-project-list'"), true), /重新启动/)
  assert.doesNotMatch(canvasProjectListError(new Error('unexpected failure'), true), /重新启动/)
})
