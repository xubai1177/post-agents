// Integration test: real Chromium frames, FFmpeg encoder and generated PCM audio.
const { app, nativeImage } = require('electron')
const { spawn, spawnSync } = require('node:child_process')
const { mkdtemp, readFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const assert = require('node:assert/strict')
app.setAppPath(process.cwd())
app.on('window-all-closed', () => {})
app.whenReady().then(async () => {
  const dir = await mkdtemp(join(tmpdir(), 'whiteboard-ffmpeg-'))
  let status = 0
  try {
    const { prepareAudioTimeline, renderChromium } = require(process.argv[2])
    const ffmpeg = join(process.cwd(), '.cache/ffmpeg/ffmpeg')
    const voice = join(dir, 'voice.wav')
    const sampleRate = 24000, data = Buffer.alloc(sampleRate * 2 * 0.4)
    for (let i = 0; i < data.length / 2; i++) data.writeInt16LE(Math.round(Math.sin(i * 2 * Math.PI * 440 / sampleRate) * 12000), i * 2)
    const wav = Buffer.alloc(44); wav.write('RIFF'); wav.writeUInt32LE(36 + data.length, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(sampleRate, 24); wav.writeUInt32LE(sampleRate * 2, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(data.length, 40)
    await require('node:fs/promises').writeFile(voice, Buffer.concat([wav, data]))
    const input = [{ beats: [{ segments: [{ text: '第一句。', audioPath: voice }, { text: '第二句。', audioPath: voice }] }] }]
    const timeline = await prepareAudioTimeline(input, dir)
    assert.equal(timeline.frames, 24)
    assert.equal(timeline.segments[1].start, 0.4)
    assert.match(await readFile(join(dir, '字幕.srt'), 'utf8'), /00:00:00,400 --> 00:00:00,800/)
    const sticker = join(dir, 'sticker.png')
    await require('node:fs/promises').writeFile(sticker, nativeImage.createFromBitmap(Buffer.from([0, 0, 255, 255]), { width: 1, height: 1 }).toPNG())
    const output = join(dir, '视频.mp4')
    const child = spawn(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-f', 'image2pipe', '-framerate', '30', '-vcodec', 'png', '-i', 'pipe:0', '-i', timeline.audioPath, '-map', '0:v:0', '-map', '1:a:0', '-c:v', 'h264_videotoolbox', '-allow_sw', '1', '-pix_fmt', 'yuv420p', '-c:a', 'aac', output], { stdio: ['pipe', 'pipe', 'pipe'] })
    let error = ''; child.stderr.on('data', chunk => { error += chunk }); child.stdout.resume()
    const completed = new Promise(resolve => { child.once('error', () => resolve(-1)); child.once('close', resolve) })
    const path = [[{ x: 0, y: -22 }, { x: 90, y: -22 }, { x: 90, y: 22 }, { x: 0, y: 22 }, { x: 0, y: -22 }]]
    const progress = []
    const warnings = await renderChromium(child, [{ focus: '测试', layout: 'diagram', relations: [{ from: { beat: 0, element: 0 }, to: { beat: 0, element: 1 }, label: '影响' }], beats: [{ stickerPath: sticker, stickerPosition: { x: 10, y: 20, width: 30, height: 30 }, elements: [{ type: 'box', text: '原因', paths: path, x: 10, y: 20, width: 30, height: 30 }, { type: 'box', text: '结果', paths: path }] }] }], timeline, () => false, (completed, total) => progress.push({ completed, total }))
    assert.deepEqual(progress[0], { completed: 0, total: timeline.frames })
    assert.deepEqual(progress.at(-1), { completed: timeline.frames, total: timeline.frames })
    assert.ok(progress.every((item, index) => item.total === timeline.frames && (!index || item.completed >= progress[index - 1].completed)))
    assert.ok(warnings.some(warning => warning.includes('场景 1') && warning.includes('重叠')), '成片应报告无法自动消除的固定位置冲突')
    assert.equal(await completed, 0, error)
    const probe = spawnSync(ffmpeg, ['-hide_banner', '-i', output, '-f', 'null', '-'], { encoding: 'utf8' })
    assert.equal(probe.status, 0, probe.stderr)
    assert.match(probe.stderr, /Video: h264/); assert.match(probe.stderr, /1920x1080/); assert.match(probe.stderr, /Audio: aac/)
    assert.match(probe.stderr, /Duration: 00:00:00\.8/)
    const noImageOutput = join(dir, '无贴纸.mp4')
    const noImageChild = spawn(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-f', 'image2pipe', '-framerate', '30', '-vcodec', 'png', '-i', 'pipe:0', '-i', timeline.audioPath, '-c:v', 'h264_videotoolbox', '-allow_sw', '1', '-pix_fmt', 'yuv420p', '-c:a', 'aac', noImageOutput], { stdio: ['pipe', 'pipe', 'pipe'] })
    let noImageError = ''; noImageChild.stderr.on('data', chunk => { noImageError += chunk }); noImageChild.stdout.resume()
    const noImageCompleted = new Promise(resolve => { noImageChild.once('error', () => resolve(-1)); noImageChild.once('close', resolve) })
    await renderChromium(noImageChild, [{ focus: '无贴纸', layout: 'list', beats: [{ elements: [{ type: 'text', text: '第二句', cue: 1 }] }] }], timeline, () => false)
    assert.equal(await noImageCompleted, 0, noImageError)
    process.stdout.write('Chromium → FFmpeg 视频、音频与字幕时间轴通过。\n')
  } catch (error) { console.error(error); status = 1 }
  finally { await rm(dir, { recursive: true, force: true }) }
  app.exit(status)
})
