const assert = require('node:assert/strict')
const { mkdtemp, readFile, writeFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { build } = require('esbuild')

;(async () => {
  const dir = await mkdtemp(join(tmpdir(), 'voice-config-test-'))
  try {
    const shim = join(dir, 'electron.cjs'), bundle = join(dir, 'voice.cjs')
    await writeFile(shim, `exports.app={getPath:()=>${JSON.stringify(dir)}};exports.safeStorage={isEncryptionAvailable:()=>true,getSelectedStorageBackend:()=>"keychain",encryptString:s=>Buffer.from("encrypted:"+s),decryptString:b=>{const s=b.toString();if(!s.startsWith("encrypted:"))throw Error();return s.slice(10)}}`)
    await writeFile(join(dir, 'whiteboard-voice-key'), 'encrypted:legacy-key')
    await build({ entryPoints: ['src/main/features/whiteboard/voice-config.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: bundle, alias: { electron: shim }, logLevel: 'silent' })
    const api = require(bundle)
    let configs = await api.listVoiceConfigs()
    assert.equal(configs.length, 1)
    assert.equal((await api.resolveVoiceConfig(configs[0].id)).key, 'legacy-key')
    configs = await api.saveVoiceConfig({ name: '备用', provider: 'agent-plan', url: 'https://voice.example.test/tts', key: 'new-key' })
    assert.equal(configs.length, 2)
    assert.equal((await api.resolveVoiceConfig(configs[1].id)).url, 'https://voice.example.test/tts')
    await api.saveVoiceConfig({ id: configs[1].id, name: '备用更新', provider: 'agent-plan', url: configs[1].url, key: '' })
    assert.equal((await api.resolveVoiceConfig(configs[1].id)).key, 'new-key')
    assert.doesNotMatch(await readFile(join(dir, 'whiteboard-voice-configs.json'), 'utf8'), /new-key|legacy-key/)
    await assert.rejects(api.saveVoiceConfig({ name: 'bad', provider: 'volcengine', url: 'http://localhost/', key: 'key' }))
    await api.deleteVoiceConfig(configs[0].id)
    assert.equal((await api.listVoiceConfigs()).length, 1)
    await assert.rejects(api.resolveVoiceConfig(configs[0].id))
    console.log('语音配置迁移、加密存储、多配置和删除检查通过')
  } finally { await rm(dir, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
