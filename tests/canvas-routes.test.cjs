const { test, after } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { randomUUID } = require('node:crypto')
const { buildSync } = require('esbuild')
const dir = mkdtempSync(join(tmpdir(), 'canvas-routes-'))
const bundle = join(dir, 'routes.cjs')
buildSync({ entryPoints: ['src/renderer/src/features/canvas-routes.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: bundle, logLevel: 'silent' })
const { isCanvasWindowRoute, canvasProjectFromRoute, canvasProjectRoute } = require(bundle)
after(() => rmSync(dir, { recursive: true, force: true }))
test('工程路由可在刷新时解析，返回列表后清除工程标识', () => {
  const id = randomUUID(), route = canvasProjectRoute(id)
  assert.equal(isCanvasWindowRoute(route), true)
  assert.equal(canvasProjectFromRoute(route), id)
  assert.equal(canvasProjectRoute(null), '#whiteboard-canvas')
  assert.equal(canvasProjectFromRoute(canvasProjectRoute(null)), null)
  assert.equal(canvasProjectFromRoute('#whiteboard-canvas?project=../../other'), null)
  assert.equal(isCanvasWindowRoute('#whiteboard-canvas-other?project=' + id), false)
})
